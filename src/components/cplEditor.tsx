'use client';
import { useId, useState } from 'react';
import { Switch } from '@/components/ui/switch';
import CplVisualEditor from '@/components/cplVisualEditor';
export default function CplEditor({
  value,
  onChange,
  disabled,
}: {
  value: string;
  onChange: (value: string) => void;
  disabled: boolean;
}) {
  const id = useId();
  const [source, setSource] = useState(false);
  const [manual, setManual] = useState(false);
  return (
    <div className='min-w-0'>
      <div className='flex flex-wrap items-center justify-between gap-3 border-b bg-muted/10 px-4 py-3'>
        <div>
          <h3 className='text-sm font-medium'>
            {source ? 'Advanced CPL source' : 'Visual policy editor'}
          </h3>
          <p className='text-xs text-muted-foreground'>
            {source
              ? 'Direct access to the same CPL draft.'
              : 'Layers, rules and reusable objects. Only the edited source ranges are changed.'}
          </p>
        </div>
        <label
          htmlFor={`${id}-source`}
          className='flex cursor-pointer items-center gap-2 text-xs'
        >
          Edit CPL source
          <Switch
            id={`${id}-source`}
            checked={source}
            onCheckedChange={setSource}
            aria-label='Edit CPL source'
          />
        </label>
      </div>
      {(source || manual) && (
        <p
          role='note'
          className='border-b border-orange-500/30 bg-orange-500/10 px-4 py-3 text-xs text-orange-800 dark:text-orange-300'
        >
          {source
            ? 'Manual changes can diverge from the structure generated by this visual editor.'
            : 'This draft contains manual source edits.'}{' '}
          Unsupported constructs are preserved and may be unavailable
          in visual controls. Switching modes does not discard your
          draft; review the diff before applying it.
        </p>
      )}
      {source ? (
        <>
          <label className='sr-only' htmlFor={`${id}-text`}>
            CPL source
          </label>
          <textarea
            id={`${id}-text`}
            spellCheck={false}
            autoCapitalize='off'
            autoComplete='off'
            wrap='off'
            value={value}
            disabled={disabled}
            onChange={(e) => {
              setManual(true);
              onChange(e.target.value);
            }}
            className='h-[min(65dvh,50rem)] min-h-80 w-full resize-y bg-muted/10 p-4 font-mono text-xs leading-5 outline-none focus-visible:ring-2 focus-visible:ring-inset focus-visible:ring-ring disabled:opacity-60'
          />
        </>
      ) : (
        <CplVisualEditor
          value={value}
          onChange={onChange}
          disabled={disabled}
        />
      )}
    </div>
  );
}
